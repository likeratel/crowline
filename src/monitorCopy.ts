const catalogs: Record<Locale, Record<Key, string>> = {
  en,
  ko,
  ja,
  "zh-CN": zhCN,
};
export function monitorCopy(
  locale: Locale,
  key: Key,
  values: TranslationValues = {},
) {
  return catalogs[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name)
      ? String(values[name])
      : match,
  );
}
